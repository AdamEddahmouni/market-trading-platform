    INVALID_TRANSITION = "OF01_INVALID_TRANSITION"
    MISSING_REFERENCE = "OF01_MISSING_REFERENCE"
    UNSUPPORTED_COMMAND_SCHEMA = "OF01_UNSUPPORTED_COMMAND_SCHEMA"
    DISPOSITION_AMBIGUOUS = "OF01_DISPOSITION_AMBIGUOUS"
    SQLITE_BUSY = "OF01_SQLITE_BUSY"
    STORAGE_UNWRITABLE = "OF01_STORAGE_UNWRITABLE"
    UNSUPPORTED_FILESYSTEM = "OF01_UNSUPPORTED_FILESYSTEM"
    MULTIPLE_WRITERS = "OF01_MULTIPLE_WRITERS"
    AMBIGUOUS_COMMIT = "OF01_AMBIGUOUS_COMMIT"
    APPEND_ONLY_UPDATE_PROHIBITED = "OF01_APPEND_ONLY_UPDATE_PROHIBITED"
    APPEND_ONLY_DELETE_PROHIBITED = "OF01_APPEND_ONLY_DELETE_PROHIBITED"
    CAS_PREPARE_FAILED = "OF01_CAS_PREPARE_FAILED"
    CAS_HASH_MISMATCH = "OF01_CAS_HASH_MISMATCH"

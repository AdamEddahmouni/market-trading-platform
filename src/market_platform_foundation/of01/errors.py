    CAS_ORPHAN_FOUND = "OF01_CAS_ORPHAN_FOUND"
    CAS_GC_AUTHORIZATION_MISMATCH = "OF01_CAS_GC_AUTHORIZATION_MISMATCH"
    INTEGRITY_FATAL = "OF01_INTEGRITY_FATAL"
    SCHEMA_UNSUPPORTED = "OF01_SCHEMA_UNSUPPORTED"
    RECORD_HASH_MISMATCH = "OF01_RECORD_HASH_MISMATCH"
    COMMIT_HASH_MISMATCH = "OF01_COMMIT_HASH_MISMATCH"
    MEMBERSHIP_MISMATCH = "OF01_MEMBERSHIP_MISMATCH"
    FOREIGN_KEY_MISMATCH = "OF01_FOREIGN_KEY_MISMATCH"
    BACKUP_INCOMPLETE = "OF01_BACKUP_INCOMPLETE"
    BACKUP_VERIFY_FAILED = "OF01_BACKUP_VERIFY_FAILED"
    RESTORE_VERIFY_FAILED = "OF01_RESTORE_VERIFY_FAILED"
    AUTHORITY_IDENTITY_MISMATCH = "OF01_AUTHORITY_IDENTITY_MISMATCH"

def _executed_review(
    *,
    review_mode: TradeReviewMode,
    opportunity_id: str | None,
    strategy_id: str | None,
    decision: str,
    decision_time_ns: int,
    created_at_ns: int,
    execution_attribution: TradeExecutionAttribution,
    execution_decision_trace_id: str | None,
    evidence_snapshot_refs: tuple[ContractReference, ...],
    preview_refs: tuple[ContractReference, ...],
    contradictions: tuple[str, ...],
    risk_snapshot: dict[str, Any] | None,
    ftep_campaign: str | None,
    ftep_session_id: str | None,
    tags: tuple[str, ...],
    mistakes: tuple[str, ...],
    notes: str,
    reflection: str,
    metadata: dict[str, Any] | None,
) -> TradeReviewV1:
    review_id = derive_trade_review_id(
        review_mode=review_mode,
        opportunity_id=opportunity_id,
        strategy_id=strategy_id,
        decision=decision,
        decision_time_ns=decision_time_ns,
        ftep_campaign=ftep_campaign,
        ftep_session_id=ftep_session_id,
        evidence_snapshot_refs=evidence_snapshot_refs,
    )
    return TradeReviewV1(
        review_id=review_id,
        schema_version=TRADE_REVIEW_SCHEMA_VERSION,
        review_mode=review_mode,
        decision=decision,
        decision_time_ns=decision_time_ns,
        created_at_ns=created_at_ns,
        opportunity_id=opportunity_id,
        strategy_id=strategy_id,
        ftep_campaign=ftep_campaign,
        ftep_session_id=ftep_session_id,
        evidence_snapshot_refs=evidence_snapshot_refs,
        contradictions=contradictions,
        risk_snapshot=risk_snapshot,
        preview_refs=preview_refs,
        execution_attribution=execution_attribution,
        execution_decision_trace_id=execution_decision_trace_id,
        tags=tags,
        mistakes=mistakes,
        notes=notes,
        reflection=reflection,
        metadata=dict(metadata or {}),
    )



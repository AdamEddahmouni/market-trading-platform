    EVALUATION_PROVIDER_SCOPE_REQUIRED = "EVALUATION_PROVIDER_SCOPE_REQUIRED"
    EVALUATION_INPUT_UNAVAILABLE = "EVALUATION_INPUT_UNAVAILABLE"
    EVALUATION_INPUT_CONFLICTED = "EVALUATION_INPUT_CONFLICTED"
    EVALUATION_INPUT_INSUFFICIENT = "EVALUATION_INPUT_INSUFFICIENT"
